#While Loops
#------------------------------
i = 1
while i <= 5:
    print(i)
    i += 1
#------------------------------
count = 3
while count > 0:
    print("Countdown:", count)
    count -= 1
#------------------------------
total = 0
num = 1
while num <= 3:
    total += num
    num += 1
print("Total:", total)
#------------------------------
word = "Python"
index = 0
while index < len(word):
    print(word[index])
    index += 1
#------------------------------
x = 1
while x < 3:
    print(x)
    x += 1
else:
    print("x is no longer less than 3")
