#For Loops
#-----------------------------------------------
fruits = ["apple", "banana", "cherry"]
for x in fruits:
    print(x)
#-----------------------------------------------
for letter in "Python":
    print(letter)
#-----------------------------------------------
for i in range(5):
    print("Номер:", i)
#-----------------------------------------------
for i in range(2, 6):
    print(i)
#-----------------------------------------------
for i in range(0, 11, 2):
    print("Четное:", i)
#-----------------------------------------------